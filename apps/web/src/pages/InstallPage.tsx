import { useEffect, useState } from 'react';
import { Navigate, useLocation, useNavigate } from 'react-router-dom';
import { Check, ChevronDown, Copy, MousePointerClick } from 'lucide-react';
import Button from '../components/ui/Button';
import FormError from '../components/ui/FormError';
import PageHeader from '../components/ui/PageHeader';
import CodeBlock from '../components/onboarding/CodeBlock';
import { muted } from '../components/ui/styles';
import { api } from '../api/client';
import type { Snippet, Sync } from '../api/client';
import { useSession } from '../api/session';

/** Where <head> is on common site builders (one line each; the snippet itself comes from the API). */
const WHERE: { name: string; how: string }[] = [
  { name: 'Plain HTML', how: 'every page, inside <head> … </head>' },
  { name: 'React / Vite', how: 'index.html, inside <head>' },
  { name: 'Next.js', how: 'app/layout.tsx: a <head> inside <html>, or next/script' },
  { name: 'WordPress', how: 'a "header and footer scripts" plugin, or the theme header' },
  { name: 'Shopify', how: 'Online Store > Themes > Edit code > theme.liquid, before </head>' },
  { name: 'Webflow / Wix / Squarespace', how: 'Settings > Custom code > Head code' },
];

/** Copy button with its own "Copied" state. */
function CopyButton({ text, label, testId }: { text: string; label: string; testId?: string }) {
  const [copied, setCopied] = useState(false);
  const copy = async () => {
    try {
      await navigator.clipboard.writeText(text);
      setCopied(true);
      setTimeout(() => setCopied(false), 1800);
    } catch {
      /* clipboard blocked: the code is selectable */
    }
  };
  return (
    <Button variant="ghost" type="button" onClick={copy} data-testid={testId} className="gap-2">
      {copied ? <Check className="size-4" /> : <Copy className="size-4" />}
      {copied ? 'Copied!' : label}
    </Button>
  );
}

/**
 * Install: ONE way, the script tag in <head> (owner decision 2026-10-12), plus optional custom-event code.
 * Both snippets are generated by the API for this site's key; nothing is composed here.
 */
export default function InstallPage() {
  const navigate = useNavigate();
  const { state } = useLocation();
  const { current } = useSession();
  const [snippets, setSnippets] = useState<Snippet[]>([]);
  const [eventsOpen, setEventsOpen] = useState(false);
  const [sync, setSync] = useState<Sync | undefined>((state as { sync?: Sync } | null)?.sync);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (!current) return;
    api.site(current.id).then((r) => setSnippets(r.snippets), (e: Error) => setError(e.message));
  }, [current]);

  if (!current) return <Navigate to="/sites/new" replace />;

  const tag = snippets.find((s) => s.group === 'script-tag');
  const events = snippets.find((s) => s.group === 'custom-event');

  const retry = async () => {
    try {
      setSync((await api.sync(current.id)).sync);
    } catch (e) {
      setSync({ ok: false, message: e instanceof Error ? e.message : 'Retry failed.' });
    }
  };

  return (
    <>
      <PageHeader
        title="Add the script to your site"
        sub={
          <>
            For <b>{current.domain}</b>. Copy this one line and paste it inside the <code className="rounded bg-slate-100 px-1 py-0.5 text-[13px] dark:bg-slate-800">&lt;head&gt;</code> of your site.
          </>
        }
      />

      {sync && !sync.ok && (
        <div role="alert" className="mb-5 flex flex-wrap items-center justify-between gap-3 rounded-xl border border-amber-300 bg-amber-50 p-4 text-sm text-amber-900 dark:border-amber-400/30 dark:bg-amber-400/10 dark:text-amber-200">
          <span>Your site is saved, but it is not active at the edge yet. {sync.message}</span>
          <Button variant="ghost" type="button" onClick={retry}>Retry activation</Button>
        </div>
      )}

      <FormError message={error} />

      {/* ------------------------------------------------------------ the one install step */}
      {tag ? (
        <>
          <CodeBlock code={tag.code} />
          {tag.note && <p className={`mt-3 text-[13px] leading-relaxed ${muted}`}>{tag.note}</p>}
          <div className="mt-4 flex flex-wrap items-center gap-3">
            <CopyButton text={tag.code} label="Copy script" testId="copy-script" />
            <Button onClick={() => navigate('/verify')}>I added it</Button>
          </div>
        </>
      ) : (
        !error && <p className={muted}>Loading…</p>
      )}

      <details className="group mt-6 rounded-xl border border-slate-200 text-sm dark:border-slate-800">
        <summary className="flex cursor-pointer list-none items-center justify-between gap-2 px-4 py-3 font-medium text-slate-700 dark:text-slate-200">
          Where is &lt;head&gt; on my site?
          <ChevronDown className="size-4 flex-none text-slate-400 transition group-open:rotate-180" />
        </summary>
        <ul className="grid gap-1.5 border-t border-slate-200 px-4 py-3 dark:border-slate-800">
          {WHERE.map((w) => (
            <li key={w.name} className="flex flex-col sm:flex-row sm:gap-2">
              <span className="font-semibold text-slate-800 sm:w-52 sm:flex-none dark:text-slate-100">{w.name}</span>
              <span className={muted}>{w.how}</span>
            </li>
          ))}
        </ul>
      </details>

      {/* ------------------------------------------------------------ optional: custom events */}
      {events && (
        <section className="mt-4 rounded-xl border border-slate-200 dark:border-slate-800" data-testid="custom-events">
          <button
            type="button"
            onClick={() => setEventsOpen((o) => !o)}
            aria-expanded={eventsOpen}
            className="flex w-full items-center gap-3 px-4 py-3 text-left"
          >
            <span className="grid size-9 flex-none place-items-center rounded-lg bg-teal-50 text-teal-700 dark:bg-teal-400/10 dark:text-teal-300">
              <MousePointerClick className="size-[18px]" />
            </span>
            <span className="min-w-0 flex-1">
              <span className="block text-sm font-semibold text-slate-900 dark:text-white">Track custom events (optional)</span>
              <span className={`block text-[13px] ${muted}`}>Count clicks, sign-ups or purchases. Copy the code and paste it where the action happens.</span>
            </span>
            <ChevronDown className={`size-4 flex-none text-slate-400 transition ${eventsOpen ? 'rotate-180' : ''}`} />
          </button>
          {eventsOpen && (
            <div className="border-t border-slate-200 p-4 dark:border-slate-800">
              <CodeBlock code={events.code} />
              {events.note && <p className={`mt-3 text-[13px] leading-relaxed ${muted}`}>{events.note}</p>}
              <div className="mt-3">
                <CopyButton text={events.code} label="Copy event code" testId="copy-events" />
              </div>
            </div>
          )}
        </section>
      )}
    </>
  );
}
