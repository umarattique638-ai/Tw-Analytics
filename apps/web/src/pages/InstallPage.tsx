import { useState } from 'react';
import { Navigate, useLocation, useNavigate } from 'react-router-dom';
import { ChevronDown, MousePointerClick } from 'lucide-react';
import Button from '../components/ui/Button';
import FormError from '../components/ui/FormError';
import Notice from '../components/ui/Notice';
import PageHeader from '../components/ui/PageHeader';
import Skeleton from '../components/ui/Skeleton';
import CodeBlock from '../components/onboarding/CodeBlock';
import { muted } from '../components/ui/styles';
import type { Sync } from '../api/client';
import { useSnippets } from '../hooks/useSetup';
import { useDocumentTitle } from '../hooks/useDocumentTitle';
import { useSession } from '../hooks/useSession';

/** Where <head> is on common site builders (one line each; the snippet itself comes from the API). */
const WHERE: { name: string; how: string }[] = [
  { name: 'Plain HTML', how: 'every page, inside <head> … </head>' },
  { name: 'React / Vite / Vue', how: 'index.html, inside <head>' },
  { name: 'Next.js', how: 'app/layout.tsx: a <head> inside <html>, or next/script' },
  { name: 'WordPress', how: 'a "header and footer scripts" plugin, or the theme header' },
  { name: 'Shopify', how: 'Online Store > Themes > Edit code > theme.liquid, before </head>' },
  { name: 'Webflow / Wix / Squarespace', how: 'Settings > Custom code > Head code' },
];

const head = <code className="rounded bg-slate-100 px-1 py-0.5 text-[13px] dark:bg-slate-800">&lt;head&gt;</code>;

/**
 * Setup step 2: ONE way to install, the script tag in <head> (owner decision 2026-10-12), plus optional
 * custom-event code. Both snippets are generated by the API for this site's key; nothing is composed here.
 */
export default function InstallPage() {
  useDocumentTitle('Install the script');
  const navigate = useNavigate();
  const { state } = useLocation();
  const { current } = useSession();
  const { tag, events, loading, error, sync, retryActivation } = useSnippets(current, (state as { sync?: Sync } | null)?.sync);
  const [eventsOpen, setEventsOpen] = useState(false);

  if (!current) return <Navigate to="/sites/new" replace />;

  return (
    <>
      <PageHeader
        compact
        title="Add the script to your site"
        description={
          <>
            For <b className="text-slate-700 dark:text-slate-200">{current.domain}</b>. Copy this one line and paste it inside the {head} of every page.
          </>
        }
      />

      {sync && !sync.ok && (
        <Notice
          tone="warning"
          className="mb-5"
          action={
            <Button variant="secondary" size="sm" onClick={retryActivation}>
              Retry activation
            </Button>
          }
        >
          Your site is saved, but it is not active at the edge yet. {sync.message}
        </Notice>
      )}

      <FormError message={error} />

      {loading && <Skeleton className="h-28 w-full rounded-xl" />}
      {tag && (
        <>
          <CodeBlock code={tag.code} copyLabel="Copy script" copyTestId="copy-script" />
          {tag.note && <p className={`mt-3 text-[13px] leading-relaxed ${muted}`}>{tag.note}</p>}
          <div className="mt-5 flex flex-wrap items-center gap-3">
            <Button onClick={() => navigate('/verify')}>I added it</Button>
            <span className={`text-[13px] ${muted}`}>Next we check your page and wait for the first visit.</span>
          </div>
        </>
      )}

      <details className="group mt-7 rounded-xl border border-slate-200 text-sm dark:border-slate-800">
        <summary className="flex cursor-pointer list-none items-center justify-between gap-2 rounded-xl px-4 py-3 font-medium text-slate-700 focus-visible:outline-none focus-visible:ring-4 focus-visible:ring-teal-600/20 dark:text-slate-200">
          Where is &lt;head&gt; on my site?
          <ChevronDown className="size-4 flex-none text-slate-400 transition group-open:rotate-180" aria-hidden="true" />
        </summary>
        <dl className="grid gap-2 border-t border-slate-200 px-4 py-3 dark:border-slate-800">
          {WHERE.map((w) => (
            <div key={w.name} className="flex flex-col sm:flex-row sm:gap-2">
              <dt className="font-semibold text-slate-800 sm:w-52 sm:flex-none dark:text-slate-100">{w.name}</dt>
              <dd className={muted}>{w.how}</dd>
            </div>
          ))}
        </dl>
      </details>

      {events && (
        <section className="mt-3 rounded-xl border border-slate-200 dark:border-slate-800" data-testid="custom-events">
          <button
            type="button"
            onClick={() => setEventsOpen((o) => !o)}
            aria-expanded={eventsOpen}
            className="flex w-full items-center gap-3 rounded-xl px-4 py-3 text-left focus-visible:outline-none focus-visible:ring-4 focus-visible:ring-teal-600/20"
          >
            <span className="grid size-9 flex-none place-items-center rounded-lg bg-teal-50 text-teal-700 dark:bg-teal-400/10 dark:text-teal-300">
              <MousePointerClick className="size-[18px]" aria-hidden="true" />
            </span>
            <span className="min-w-0 flex-1">
              <span className="block text-sm font-semibold text-slate-900 dark:text-white">Track custom events (optional)</span>
              <span className={`block text-[13px] ${muted}`}>Count clicks, sign-ups or purchases. Paste the code where the action happens.</span>
            </span>
            <ChevronDown className={`size-4 flex-none text-slate-400 transition ${eventsOpen ? 'rotate-180' : ''}`} aria-hidden="true" />
          </button>
          {eventsOpen && (
            <div className="border-t border-slate-200 p-4 dark:border-slate-800">
              <CodeBlock code={events.code} copyLabel="Copy event code" copyTestId="copy-events" />
              {events.note && <p className={`mt-3 text-[13px] leading-relaxed ${muted}`}>{events.note}</p>}
            </div>
          )}
        </section>
      )}
    </>
  );
}
